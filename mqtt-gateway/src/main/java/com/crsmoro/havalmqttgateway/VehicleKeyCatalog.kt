package com.crsmoro.havalmqttgateway

import java.util.Collections

/**
 * Vehicle telemetry identifiers, not an access-control list or an availability promise.
 * OEM_PROPERTY means named by the OEM-facing vocabulary, not verified readable on a
 * particular car. Non-default keys require source-side monitoring and actual support;
 * a default subscription likewise does not guarantee a value. Some status/settings
 * properties may also be writable elsewhere; this catalog performs no operations.
 * The sensitive flag highlights explicit identifiers and occupant data; it does not
 * imply that other telemetry cannot reveal private information.
 *
 * The facts are interoperability identifiers from the locally inspected producer's
 * vocabulary and its default subscriptions. No producer implementation is included.
 * Synthetic power signals originate in the producer, not in the OEM property service.
 * Deliberately excludes app, navigation, phone, unrelated system and command keys.
 */
object VehicleKeyCatalog {
    enum class Source { OEM_PROPERTY, APP_SYNTHETIC }

    data class Entry(
        val key: String,
        val source: Source,
        val defaultMonitored: Boolean,
        val sensitive: Boolean,
        val note: String? = null
    )

    private fun names(raw: String): List<String> = raw.trimIndent().lineSequence()
        .map(String::trim).filter(String::isNotEmpty).toList()

    // A distinct set prevents duplicates in upstream subscriptions becoming duplicate entries.
    private val defaultKeys = names(DEFAULT_NAMES).toSet()
    private val notes = mapOf(
        "car.basic.tpms_status" to "Observed as four pressure-in-bar/temperature-in-C pairs; wheel order is unconfirmed.",
        "car.basic.tpms_units" to "Unit indicator for tyre telemetry; interpretation may vary by vehicle.",
        "car.basic.engine_state" to "Reported engine/ignition state does not by itself prove combustion is running.",
        "haval.power.flow" to "Producer-derived v1|state|ice|front|rear; present only when derivable.",
        "haval.power.ice" to "Producer-derived combustion indicator (1 or 0), gated by engine speed."
    )
    private val sensitiveKeys = setOf(
        "car.basic.vin_code", "car.basic.seated_state", "car.basic.seat_belt_warning",
        "car.ipk_light.seat_belt_warning_indicator"
    )
    private val index: Map<String, Entry> = buildMap {
        for (key in names(OEM_NAMES).distinct()) {
            val sensitive = key in sensitiveKeys ||
                key.startsWith("car.dms.") || key.startsWith("car.frs_setting.") ||
                key.startsWith("car.oms.")
            put(key, Entry(key, Source.OEM_PROPERTY, key in defaultKeys, sensitive, notes[key]))
        }
        for (key in listOf("haval.power.flow", "haval.power.ice")) {
            put(key, Entry(key, Source.APP_SYNTHETIC, false, false, notes[key]))
        }
    }

    /** Stable, immutable snapshot of known names, in exact case. */
    val entries: List<Entry> = Collections.unmodifiableList(index.values.toList())

    /** Exact-match lookup; unknown names are not silently normalized or invented. */
    fun find(key: String): Entry? = index[key]

